#!/bin/bash
# /usr/local/bin/update-cloudflare-ips.sh
# Single source of truth for Cloudflare IP ranges on this VPS. Regenerates:
#
#   1) /nginx/conf/cloudflare-ips.geo
#      nginx's "geo $conn_src_ip $from_cf" depends on it to tell CF traffic
#      apart. A stale file makes requests from new CF ranges log the CF edge
#      IP as $client_ip instead of the user's real IP.
#
#   2) /etc/fail2ban/jail.d/01-ignoreip.local
#      fully OWNED by this script - never edit it by hand. Permanent custom
#      safe-list entries belong in /etc/fail2ban/ignoreip.custom (one per
#      line, # comments allowed); they are merged on every run.
#
# Target-tolerant: updates whichever of the two targets exists and reloads
# only services that are actually running, so it can be called at any point
# of the deployment (phase2 calls it before fail2ban exists; fail2ban's
# deploy.sh calls it again once the jails are in place; a monthly cron
# keeps both fresh).

set -euo pipefail

CF_V4_URL="https://www.cloudflare.com/ips-v4"
CF_V6_URL="https://www.cloudflare.com/ips-v6"

NGINX_CONF_DIR="/nginx/conf"
NGINX_GEO="$NGINX_CONF_DIR/cloudflare-ips.geo"
NGINX_BIN="/nginx/sbin/nginx"

F2B_JAILD="/etc/fail2ban/jail.d"
F2B_IGNOREIP="$F2B_JAILD/01-ignoreip.local"
CUSTOM_IGNOREIP="/etc/fail2ban/ignoreip.custom"

if [ "${EUID:-$(id -u)}" -ne 0 ]; then
    echo "ERROR: Please run as root."
    exit 1
fi

HAVE_NGINX=0; [ -d "$NGINX_CONF_DIR" ] && HAVE_NGINX=1
HAVE_F2B=0;   [ -d "$F2B_JAILD" ] && HAVE_F2B=1

if [ "$HAVE_NGINX" -eq 0 ] && [ "$HAVE_F2B" -eq 0 ]; then
    echo "ERROR: neither $NGINX_CONF_DIR nor $F2B_JAILD exists - nothing to update."
    exit 1
fi

TMPDIR="$(mktemp -d)"
trap 'rm -rf "$TMPDIR"' EXIT

echo "[*] Fetching Cloudflare IP ranges..."
curl -fsS --connect-timeout 10 --max-time 30 "$CF_V4_URL" > "$TMPDIR/v4.txt"
curl -fsS --connect-timeout 10 --max-time 30 "$CF_V6_URL" > "$TMPDIR/v6.txt"
sed -i '/^[[:space:]]*$/d' "$TMPDIR/v4.txt" "$TMPDIR/v6.txt"

# Validate: CF currently publishes ~15 v4 and ~7 v6 ranges, all plain CIDRs.
if [ "$(wc -l < "$TMPDIR/v4.txt")" -lt 10 ] || [ "$(wc -l < "$TMPDIR/v6.txt")" -lt 3 ]; then
    echo "ERROR: Downloaded Cloudflare IP list is suspiciously short. Aborting."
    exit 1
fi
if grep -qvE '^[0-9a-fA-F.:]+/[0-9]+$' "$TMPDIR/v4.txt" "$TMPDIR/v6.txt"; then
    echo "ERROR: Downloaded Cloudflare IP list contains non-CIDR lines. Aborting."
    exit 1
fi

# ── nginx geo file ──────────────────────────────────────────────────
if [ "$HAVE_NGINX" -eq 1 ]; then
    echo "[*] Updating nginx geo: $NGINX_GEO"
    {
        echo "# Cloudflare IP ranges - auto-generated $(date -Iseconds)"
        echo "# Source: $CF_V4_URL + $CF_V6_URL"
        echo "# Generated by update-cloudflare-ips.sh - do not edit."
        # No "default 0;" here: the geo block in nginx.conf already defines it.
        while IFS= read -r cidr; do echo "$cidr 1;"; done < "$TMPDIR/v4.txt"
        while IFS= read -r cidr; do echo "$cidr 1;"; done < "$TMPDIR/v6.txt"
    } > "$TMPDIR/cloudflare-ips.geo"

    [ -f "$NGINX_GEO" ] && cp -p "$NGINX_GEO" "$TMPDIR/geo.prev"
    cp "$TMPDIR/cloudflare-ips.geo" "$NGINX_GEO"
    chown root:root "$NGINX_GEO"
    chmod 644 "$NGINX_GEO"

    if [ -x "$NGINX_BIN" ]; then
        if ! "$NGINX_BIN" -t; then
            echo "ERROR: nginx config test failed with the new geo file."
            if [ -f "$TMPDIR/geo.prev" ]; then
                cp -p "$TMPDIR/geo.prev" "$NGINX_GEO"
                echo "    Previous geo file restored."
            fi
            exit 1
        fi
        if pgrep -x nginx >/dev/null 2>&1; then
            "$NGINX_BIN" -s reload
            echo "[+] nginx geo updated, nginx reloaded."
        else
            echo "[+] nginx geo updated (nginx not running - picked up on next start)."
        fi
    else
        echo "[+] nginx geo updated ($NGINX_BIN not found - config not tested)."
    fi
else
    echo "[i] $NGINX_CONF_DIR not found - skipping nginx geo update."
fi

# ── fail2ban ignoreip drop-in ───────────────────────────────────────
if [ "$HAVE_F2B" -eq 1 ]; then
    echo "[*] Regenerating $F2B_IGNOREIP"
    {
        echo "# /etc/fail2ban/jail.d/01-ignoreip.local"
        echo "# Auto-generated by update-cloudflare-ips.sh $(date -Iseconds) - DO NOT EDIT."
        echo "# Permanent custom entries: $CUSTOM_IGNOREIP (one per line)."
        echo "#"
        echo "# CF ranges must stay ignored: some error.log lines record CF edge IPs,"
        echo "# and banning one cuts all CDN traffic."
        echo "[DEFAULT]"
        printf 'ignoreip = 127.0.0.1/8\n'
        printf '           ::1\n'
        if [ -f "$CUSTOM_IGNOREIP" ]; then
            while IFS= read -r entry; do
                entry="${entry%%#*}"
                entry="${entry//[[:space:]]/}"
                [ -n "$entry" ] && printf '           %s\n' "$entry"
            done < "$CUSTOM_IGNOREIP"
        fi
        while IFS= read -r cidr; do printf '           %s\n' "$cidr"; done < "$TMPDIR/v4.txt"
        while IFS= read -r cidr; do printf '           %s\n' "$cidr"; done < "$TMPDIR/v6.txt"
    } > "$TMPDIR/01-ignoreip.local"

    [ -f "$F2B_IGNOREIP" ] && cp -p "$F2B_IGNOREIP" "$TMPDIR/ignoreip.prev"
    cp "$TMPDIR/01-ignoreip.local" "$F2B_IGNOREIP"
    chown root:root "$F2B_IGNOREIP"
    chmod 644 "$F2B_IGNOREIP"

    if command -v fail2ban-client >/dev/null 2>&1; then
        if ! fail2ban-client -t >/dev/null; then
            echo "ERROR: fail2ban config test failed with the new ignoreip file."
            if [ -f "$TMPDIR/ignoreip.prev" ]; then
                cp -p "$TMPDIR/ignoreip.prev" "$F2B_IGNOREIP"
                echo "    Previous ignoreip file restored."
            else
                rm -f "$F2B_IGNOREIP"
                echo "    New ignoreip file removed."
            fi
            exit 1
        fi
        if systemctl is-active --quiet fail2ban 2>/dev/null; then
            fail2ban-client reload >/dev/null
            echo "[+] fail2ban ignoreip updated, fail2ban reloaded."
        else
            echo "[+] fail2ban ignoreip updated (fail2ban not running - picked up on start)."
        fi
    else
        echo "[+] fail2ban ignoreip updated (fail2ban-client not found - config not tested)."
    fi
else
    echo "[i] $F2B_JAILD not found - skipping fail2ban ignoreip update."
fi

echo "[+] Done. Cloudflare ranges: $(wc -l < "$TMPDIR/v4.txt") IPv4, $(wc -l < "$TMPDIR/v6.txt") IPv6."
